  INDEX idx_sched_due (status, publish_at),
  CONSTRAINT fk_sched_ed FOREIGN KEY (edition_id) REFERENCES editions(id) ON DELETE CASCADE,
  CONSTRAINT fk_sched_user FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB ROW_FORMAT=DYNAMIC DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS comments (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  edition_id INT UNSIGNED NOT NULL,
  page_id INT UNSIGNED NULL,
  user_id INT UNSIGNED NOT NULL,
