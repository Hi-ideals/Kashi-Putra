  INDEX idx_am_state (state_id, district_id, city_id),
  CONSTRAINT fk_am_state FOREIGN KEY (state_id) REFERENCES states(id) ON DELETE CASCADE,
  CONSTRAINT fk_am_district FOREIGN KEY (district_id) REFERENCES districts(id) ON DELETE CASCADE,
  CONSTRAINT fk_am_city FOREIGN KEY (city_id) REFERENCES cities(id) ON DELETE CASCADE,
  CONSTRAINT fk_am_region FOREIGN KEY (region_id) REFERENCES regions(id) ON DELETE CASCADE,
  CONSTRAINT fk_am_cat FOREIGN KEY (category_id) REFERENCES edition_categories(id) ON DELETE CASCADE,
  CONSTRAINT fk_am_ed FOREIGN KEY (edition_id) REFERENCES editions(id) ON DELETE CASCADE
) ENGINE=InnoDB ROW_FORMAT=DYNAMIC DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS edition_schedules (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  edition_id INT UNSIGNED NOT NULL,
  publish_at DATETIME NOT NULL,
  status ENUM('pending','completed','cancelled','failed') NOT NULL DEFAULT 'pending',
  notify_on_publish TINYINT(1) NOT NULL DEFAULT 1,
  notes VARCHAR(255) NULL,
  executed_at DATETIME NULL,
  error_message VARCHAR(500) NULL,
  created_by INT UNSIGNED NULL,
